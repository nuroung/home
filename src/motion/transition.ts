import type { Transition } from 'motion/react'

// A↔B 전환의 모든 타이밍은 이 파일 한 곳에서만 정한다.
// 각 항목은 시간순으로 정렬돼 있고, at = 시작(초), duration = 길이(초).
// 화면 쪽은 tr(cue) 로 Motion 의 transition 에 그대로 꽂아 쓴다.

export type Ease = [number, number, number, number]

/** CSS 의 `ease` */
export const CSS_EASE: Ease = [0.25, 0.1, 0.25, 1]

export interface Cue {
  at: number
  duration: number
  ease: Ease
}

const cue = (at: number, duration: number, ease: Ease = CSS_EASE): Cue => ({ at, duration, ease })

export const tr = (c: Cue): Transition => ({ delay: c.at, duration: c.duration, ease: c.ease })

